"""Generate data/passages.ttl from the cached SuttaCentral files.

Scans data/*.ttl for passage references such as dho:p-sn46.51-16.2, looks up
the exact English (Sujato) and Pali (Mahāsaṅgīti) text of each segment in
sources/suttacentral/, and writes one dho:Passage per reference, plus one
dho:Text per sutta. Quotes are never typed by hand.

Run:  python scripts/build_passages.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from rdflib import Graph, Literal, Namespace, URIRef
from rdflib.namespace import DCTERMS, RDF, SKOS, XSD

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sc import load as load_segments, stem_for, title  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "sources" / "suttacentral"
OUT = ROOT / "data" / "passages.ttl"
DHO = Namespace("https://guoxiangng.github.io/dhamma-ontology/ns#")

# Passage reference in the data: dho:p-<text uid>-<segment>, e.g. p-sn46.51-16.2
REF = re.compile(r"dho:p-([a-z]+\d+(?:\.\d+)?)-(\d+(?:\.\d+)*)")

# Titles come from each text's own header (scripts/sc.py); chunked texts are found via the canon index.



def main() -> int:
    refs: set[tuple[str, str]] = set()
    for ttl in sorted((ROOT / "data").glob("*.ttl")):
        if ttl.name == OUT.name:
            continue
        refs.update(REF.findall(ttl.read_text(encoding="utf-8")))

    g = Graph()
    g.bind("dho", DHO)
    g.bind("skos", SKOS)
    g.bind("dct", DCTERMS)

    missing = []
    cache: dict[str, tuple[dict, dict]] = {}
    for uid, seg in sorted(refs):
        if uid not in cache:
            cache[uid] = load_segments(uid)
        en, pi = cache[uid]
        seg_id = f"{uid}:{seg}"
        if seg_id not in pi and seg_id not in en:
            missing.append(seg_id)
            continue

        p = DHO[f"p-{uid}-{seg}"]
        t = DHO[f"t-{uid}"]
        g.add((p, RDF.type, DHO.Passage))
        g.add((p, DHO.inText, t))
        g.add((p, DHO.segment, Literal(seg_id)))
        if en.get(seg_id, "").strip():
            g.add((p, DHO.textEn, Literal(en[seg_id].strip(), lang="en")))
        if pi.get(seg_id, "").strip():
            g.add((p, DHO.textPi, Literal(pi[seg_id].strip(), lang="pi")))
        g.add((p, DHO.url, Literal(f"https://suttacentral.net/{uid}/en/sujato#{seg_id}", datatype=XSD.anyURI)))

    for uid in sorted({u for u, _ in refs}):
        t = DHO[f"t-{uid}"]
        g.add((t, RDF.type, DHO.Text))
        g.add((t, SKOS.prefLabel, Literal(title(uid, *cache[uid]), lang="en")))
        g.add((t, DHO.layer, DHO.SuttaLayer))
        g.add((t, DHO.url, Literal(f"https://suttacentral.net/{uid}/en/sujato", datatype=XSD.anyURI)))
        g.add((t, DCTERMS.license, URIRef("https://creativecommons.org/publicdomain/zero/1.0/")))
        g.add((t, DCTERMS.source, Literal("SuttaCentral bilara-data: English by Bhikkhu Sujato, Pali Mahāsaṅgīti edition")))

    header = (
        "# GENERATED by scripts/build_passages.py from sources/suttacentral/ — do not edit by hand.\n"
        "# Texts: SuttaCentral (CC0). English: Bhikkhu Sujato. Pali: Mahāsaṅgīti edition.\n\n"
    )
    OUT.write_text(header + g.serialize(format="turtle"), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(refs) - len(missing)} passages, {len({u for u, _ in refs})} texts")
    if missing:
        print("MISSING segments (fix the reference or fetch the text):", ", ".join(missing))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
