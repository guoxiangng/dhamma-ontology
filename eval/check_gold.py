"""Check the golden question set against the source text, and write a review sheet.

    python eval/check_gold.py

Checks (exit 1 on any failure):
  - ids unique, required fields present, category/scope/layer values known
  - every segment in `segments` and `also_ok_segments` exists in sources/suttacentral/
  - every Pali term written in brackets in a gold point, e.g. "(subhanimitta)",
    appears in the Pali of that question's cited segments (so a term recalled
    wrongly from memory fails instead of becoming 'gold')

Writes eval/GOLD-REVIEW.md: each question with its gold answer and the exact
English and Pali of every cited segment, for a human to check line by line.
"""

from __future__ import annotations

import json
import re
import sys
import tomllib
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from sc import stem_for  # noqa: E402
SOURCES = ROOT / "sources" / "suttacentral"
QUESTIONS = ROOT / "eval" / "questions.toml"
REVIEW = ROOT / "eval" / "GOLD-REVIEW.md"

CATEGORIES = {"recall", "list", "partial", "trap", "derived", "layer", "plain", "sense", "citation", "scope"}
SCOPES = {"covered", "partial", "outside"}
LAYERS = {"sutta", "commentary", "mixed"}
ENGLISH = {"to", "the", "of", "and", "with", "not", "a", "an", "in", "is", "it", "or", "for", "if", "different", "objects", "etc", "eg"}
PALI_IN_BRACKETS = re.compile(r"\(([^()]+)\)")


def fold(s: str) -> str:
    s = unicodedata.normalize("NFKD", s.lower())
    return "".join(c for c in s if not unicodedata.combining(c) and c.isalpha())


_cache: dict[str, tuple[dict, dict]] = {}


def segment(seg: str) -> tuple[str, str] | None:
    uid = seg.split(":")[0]
    if uid not in _cache:
        stem = stem_for(uid)
        try:
            _cache[uid] = tuple(json.loads((SOURCES / f"{stem}_{lang}.json").read_text(encoding="utf-8"))
                                for lang in ("en", "pli"))
        except FileNotFoundError:
            _cache[uid] = ({}, {})
    en, pi = _cache[uid]
    if seg not in en and seg not in pi:
        return None
    return en.get(seg, "").strip(), pi.get(seg, "").strip()


def pali_terms(point: str) -> list[str]:
    terms = []
    for inner in PALI_IN_BRACKETS.findall(point):
        words = re.findall(r"[^\W\d_]+", inner)
        if not words or any(w.lower() in ENGLISH for w in words) or any(c in inner for c in ",.;:'"):
            continue
        terms.append(inner)
    return terms


def term_found(term: str, pali_text: str) -> bool:
    t = fold(term)
    stem = t[:-1] if len(t) > 4 else t  # tolerate case endings: kāmacchanda -> kāmacchandassa
    return stem in pali_text


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    qs = tomllib.loads(QUESTIONS.read_text(encoding="utf-8"))["q"]
    errors: list[str] = []
    seen = set()
    checked_terms = 0
    review = ["# Gold answer review sheet", "",
              "_Generated by `eval/check_gold.py`. For each question, read the gold answer against the quoted "
              "text. When it is right, change its `status` in `questions.toml` from `draft` to `checked`._", ""]

    for q in qs:
        qid = q.get("id", "?")
        for field in ("id", "category", "scope", "question", "gold", "segments", "must_not", "layer", "status"):
            if field not in q:
                errors.append(f"{qid}: missing field '{field}'")
        if qid in seen:
            errors.append(f"{qid}: duplicate id")
        seen.add(qid)
        if q.get("category") not in CATEGORIES:
            errors.append(f"{qid}: unknown category {q.get('category')}")
        if q.get("scope") not in SCOPES:
            errors.append(f"{qid}: unknown scope {q.get('scope')}")
        if q.get("layer") not in LAYERS:
            errors.append(f"{qid}: unknown layer {q.get('layer')}")
        if q.get("scope") != "outside" and q.get("category") != "layer" and not q.get("segments"):
            errors.append(f"{qid}: a covered question needs at least one segment")

        quotes = []
        for seg in q.get("segments", []) + q.get("also_ok_segments", []):
            found = segment(seg)
            if found is None:
                errors.append(f"{qid}: segment {seg} not found in sources/suttacentral/")
            else:
                quotes.append((seg, *found, seg in q.get("also_ok_segments", [])))

        pali_blob = fold(" ".join(pi for seg, _, pi, extra in quotes if not extra))
        for point in q.get("gold", []):
            for term in pali_terms(point):
                checked_terms += 1
                if not term_found(term, pali_blob):
                    errors.append(f"{qid}: Pali term '{term}' not found in the cited segments")

        review += [f"## {qid} · {q['category']} · scope: {q['scope']} · status: {q['status']}", "",
                   f"**Q:** {q['question']}", "", "**Gold:**"]
        review += [f"- {p}" for p in q["gold"]]
        if quotes:
            review += ["", "**Text:**"]
            for seg, en, pi, extra in quotes:
                tag = " _(also acceptable source)_" if extra else ""
                uid = seg.split(":")[0]
                review.append(f"- [`{seg}`](https://suttacentral.net/{uid}/en/sujato#{seg}){tag} {en}  \n  _{pi}_")
        if q.get("also_ok"):
            review += ["", "**Also acceptable:**"] + [f"- {a}" for a in q["also_ok"]]
        if q.get("must_not"):
            review += ["", "**Fails if it says:**"] + [f"- {m}" for m in q["must_not"]]
        if q.get("note"):
            review += ["", f"> {q['note']}"]
        review.append("")

    REVIEW.write_text("\n".join(review), encoding="utf-8")
    by_status: dict[str, int] = {}
    for q in qs:
        by_status[q.get("status", "?")] = by_status.get(q.get("status", "?"), 0) + 1
    print(f"{len(qs)} questions; {checked_terms} Pali terms checked against the cited Pali; "
          f"status: {by_status}; wrote {REVIEW.relative_to(ROOT)}")
    for e in errors:
        print("  FAIL", e)
    print("PASS" if not errors else f"{len(errors)} problem(s)")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
